import React from 'react'
import { render, screen, fireEvent, within } from '@testing-library/react'
import { Harness } from './__testing__/costHarness'

const SQFT_PER_M2 = 10.76391042
const OVERHEAD = 'Installed prices are assumed to include contractor overhead, profit and waste.'
const lineButton = name => screen.getByRole('button', { name: new RegExp(`^${name}`) })
const detail = () => within(document.querySelector('.line-detail'))
const lineOrder = () => [...document.querySelectorAll('.category-line:not(.total-line) .line-name')].map(e => e.textContent)
const openSpecifics = (line, label) => { fireEvent.click(lineButton(line)); fireEvent.click(screen.getByRole('button', { name: new RegExp(`^${label}`) })) }
const startEditing = () => fireEvent.click(screen.getByRole('button', { name: /Use my own prices/ }))
const typeInto = (name, value) => {
  const input = screen.getByRole('spinbutton', { name })
  fireEvent.change(input, { target: { value: String(value) } })
  fireEvent.keyDown(input, { key: 'Enter' })
}

describe('CostTab statement', () => {
  it('shows the empty state when nothing is picked', () => {
    render(<Harness />)
    expect(screen.getByText(/Pick options on the Points tab/)).toBeInTheDocument()
    expect(within(screen.getByText(/Pick options on the Points tab/).closest('section')).getByText(/Typical Tier 2/)).toBeInTheDocument()
  })
  it('headline, sorted lines; a line opens to the Basic view and its chevron opens the specifics', () => {
    render(<Harness selections={{ hrv: 2, windowsDoors: 1, airTightness: 2 }} wallSelection={{ simpleIndex: 5 }} />)
    expect(screen.getByRole('heading', { level: 2, name: /more than Typical Tier 2, before HST/ })).toBeInTheDocument()
    expect(lineOrder().at(-1)).toBe('Heated volume')
    const walls = lineButton('Above-ground walls')
    expect(walls).toHaveAttribute('aria-expanded', 'false')
    expect(walls.querySelector('svg')).not.toBeNull()
    fireEvent.click(walls)
    expect(walls).toHaveAttribute('aria-expanded', 'true')
    expect(detail().getByText('This design', { selector: '.tile span' })).toBeInTheDocument()
    expect(detail().getByRole('note')).toHaveTextContent('You picked this wall by RSI level')
    expect(detail().getByText(/from your house fields/)).toBeInTheDocument()
    expect(screen.queryByTestId('specifics-aboveGroundWalls')).toBeNull()
    const layers = screen.getByRole('button', { name: /^Layers/ })
    expect(layers).toHaveTextContent(/\d+ layers, \d+ differ/)
    fireEvent.click(layers)
    expect(screen.getByTestId('specifics-aboveGroundWalls')).toBeInTheDocument()
    fireEvent.click(layers)
    expect(screen.queryByTestId('specifics-aboveGroundWalls')).toBeNull()
  })
  it('lines with nothing to open are not buttons', () => {
    render(<Harness selections={{ hrv: 2 }} />)
    expect(screen.queryByRole('button', { name: /^Below-grade walls/ })).toBeNull()
    expect(screen.queryByRole('button', { name: /^Heated volume/ })).toBeNull()
    expect(screen.getAllByText(/not selected - treated as the same as Typical Tier 2/).length).toBeGreaterThan(0)
  })
  it('changing the house type clears field overrides with a notice and mini-home drops below grade', () => {
    render(<Harness selections={{ hrv: 2 }} />)
    fireEvent.change(screen.getByLabelText('Storeys'), { target: { value: '3' } })
    expect(screen.getByText('changed')).toBeInTheDocument()
    fireEvent.change(screen.getByLabelText('Type'), { target: { value: 'miniHome' } })
    expect(screen.queryByText('changed')).toBeNull()
    expect(screen.getByText(/not applicable \(no foundation wall\)/)).toBeInTheDocument()
  })
  it('bedrooms above 5 reveals the designed airflow field and the ventilation line asks for it', () => {
    render(<Harness selections={{ hrv: 1 }} />)
    fireEvent.change(screen.getByLabelText('Bedrooms'), { target: { value: 'moreThan5' } })
    expect(screen.getByLabelText('Designed airflow (L/s)')).toBeInTheDocument()
    expect(screen.getByText(/enter the designed airflow/)).toBeInTheDocument()
  })
  it('the open line is its own card: the list splits around it', () => {
    render(<Harness selections={{ hrv: 2, windowsDoors: 1 }} />)
    fireEvent.click(lineButton('Ventilation'))
    expect(lineButton('Ventilation').closest('.category-line')).toHaveClass('open')
    expect(document.querySelectorAll('.category-line.open')).toHaveLength(1)
  })
})

describe('CostTab specifics and edit mode (R3 amended, R36)', () => {
  it('stores an m2 component price typed in $/sq ft as $/m2; doors pass through', () => {
    const onOverride = vi.fn()
    render(<Harness selections={{ windowsDoors: 1 }} spies={{ onOverride }} />)
    openSpecifics('Windows and doors', 'U-values and areas')
    startEditing()
    typeInto('This design windows material', 2.5)
    const [side, cat, comp, , field, v] = onOverride.mock.calls[0]
    expect([side, cat, comp, field]).toEqual(['design', 'windowsDoors', 'windows', 'material'])
    expect(v).toBeCloseTo(2.5 * SQFT_PER_M2, 9)
    typeInto('This design exterior doors material', 950)
    expect(onOverride.mock.calls[1]).toEqual(['design', 'windowsDoors', 'doors', 'u_1_22', 'material', 950])
  })
  it('converts a line price on an m2 line and passes a per-unit line through', () => {
    const onLineOverride = vi.fn()
    render(<Harness selections={{ windowsDoors: 1, hrv: 2 }} spies={{ onLineOverride }} />)
    openSpecifics('Windows and doors', 'U-values and areas')
    startEditing()
    typeInto('I pay this much per sq ft of windows for This design', 12)
    expect(onLineOverride.mock.calls[0][0]).toBe('design')
    expect(onLineOverride.mock.calls[0][1]).toBe('windowsDoors')
    expect(onLineOverride.mock.calls[0][2]).toBeCloseTo(12 * SQFT_PER_M2, 9)
    openSpecifics('Ventilation', 'Flow rates and SRE')
    startEditing()
    typeInto('I pay this much per HRV, installed for This design', 900)
    expect(onLineOverride).toHaveBeenLastCalledWith('design', 'hrv', 900)
  })
  it('passes the per-card changed count and resets that card', () => {
    const onResetCategoryOverrides = vi.fn()
    render(<Harness selections={{ windowsDoors: 1 }} overrides={{ 'design/windowsDoors/doors/u_1_22': { material: 900, labour: 100 } }} spies={{ onResetCategoryOverrides }} />)
    openSpecifics('Windows and doors', 'U-values and areas')
    startEditing()
    expect(screen.getByText(/You've changed 1 price on this card/)).toBeInTheDocument()
    fireEvent.click(within(screen.getByTestId('specifics-windowsDoors')).getByRole('button', { name: 'reset all' }))
    expect(onResetCategoryOverrides).toHaveBeenCalledWith('windowsDoors')
  })
  it('Done leaves edit mode; closing the specifics or the line leaves it too', () => {
    render(<Harness selections={{ windowsDoors: 1 }} />)
    openSpecifics('Windows and doors', 'U-values and areas')
    startEditing()
    fireEvent.click(screen.getByRole('button', { name: 'Done' }))
    expect(screen.queryByRole('spinbutton', { name: 'This design windows material' })).toBeNull()
    startEditing()
    fireEvent.click(screen.getByRole('button', { name: /^U-values and areas/ }))
    fireEvent.click(screen.getByRole('button', { name: /^U-values and areas/ }))
    expect(screen.getByRole('button', { name: /Use my own prices/ })).toBeInTheDocument()
  })
  it('notes under the table: shape and overhead; no price source; the windows total adds up', () => {
    render(<Harness selections={{ windowsDoors: 1 }} />)
    openSpecifics('Windows and doors', 'U-values and areas')
    expect(detail().getByText('Based on a single detached house, 33 x 30 ft (10.1 x 9.1 m); other shapes will differ.')).toBeInTheDocument()
    expect(detail().getByText(OVERHEAD)).toBeInTheDocument()
    expect(detail().queryByText(/^Prices: /)).toBeNull()
    expect(detail().queryByText('Items identical on both sides are priced and cancel in the difference.')).toBeNull()
    const num = t => Number(t.replace(/[^\d.-]/g, ''))
    const diffs = [...document.querySelectorAll('.specifics-table tbody tr .diff')].map(e => num(e.textContent))
    const total = num(within(screen.getByRole('row', { name: 'total' })).getAllByRole('cell').at(-1).textContent)
    expect(Math.abs(diffs.reduce((a, b) => a + b, 0) - total)).toBeLessThanOrEqual(2)
  })
  it('below grade: the plain notice and the assembly rows', () => {
    render(<Harness selections={{ belowGradeWalls: 0 }} />)
    openSpecifics('Below-grade walls', 'Assembly')
    expect(detail().getByRole('note')).toHaveTextContent('There is no foundation builder yet')
    expect(screen.getByRole('row', { name: 'Foam against the concrete' })).toHaveClass('differs')
  })
  it('water heating names its fuel and the gas note', () => {
    render(<Harness selections={{ dhwGas: 1 }} />)
    openSpecifics('Water heating', 'Heater and parts')
    expect(within(screen.getByRole('row', { name: 'Fuel' })).getByText('natural gas')).toBeInTheDocument()
    expect(detail().getByText('Gas heaters are priced as natural gas.')).toBeInTheDocument()
  })
  it('walls: the level description, the Typical Tier 2 assembly, and the rim joist note', () => {
    render(<Harness wallSelection={{ simpleIndex: 5 }} />)
    expect(lineButton('Above-ground walls')).toHaveTextContent('Typical Tier 2: RSI 3.99 (2x6 R24 batt + 1 in XPS, OSB, vinyl)')
    openSpecifics('Above-ground walls', 'Layers')
    expect(detail().getByText(/RSI 4\.4 level, priced as 2x6 R20 batt \+ 2 in XPS, OSB, vinyl/)).toBeInTheDocument()
    expect(detail().getByText('Rim joists are the same in both houses and are not priced.')).toBeInTheDocument()
  })
  it('Go to Points calls up to App', () => {
    const onGoToPoints = vi.fn()
    render(<Harness wallSelection={{ simpleIndex: 5 }} spies={{ onGoToPoints }} />)
    fireEvent.click(lineButton('Above-ground walls'))
    fireEvent.click(screen.getByRole('button', { name: 'Go to Points' }))
    expect(onGoToPoints).toHaveBeenCalledTimes(1)
  })
})

describe('CostTab open lines and order (R40)', () => {
  it('closes an open line that stops applying', () => {
    render(<Harness selections={{ belowGradeWalls: 0, hrv: 2 }} />)
    fireEvent.click(lineButton('Below-grade walls'))
    expect(document.querySelector('.line-detail')).not.toBeNull()
    fireEvent.change(screen.getByLabelText('Type'), { target: { value: 'miniHome' } })
    expect(document.querySelector('.line-detail')).toBeNull()
    expect(screen.queryByRole('button', { name: /^Below-grade walls/ })).toBeNull()
    expect(lineOrder().at(-1)).toBe('Below-grade walls')
  })
  it('keeps the order while a line is open and re-sorts when it closes', () => {
    render(<Harness selections={{ windowsDoors: 1, airTightness: 2 }} />)
    expect(lineOrder().slice(0, 2)).toEqual(['Windows and doors', 'Airtightness'])
    fireEvent.click(lineButton('Airtightness'))
    fireEvent.change(screen.getByLabelText('Glazing ratio (%)'), { target: { value: '5' } })
    expect(lineOrder().slice(0, 2)).toEqual(['Windows and doors', 'Airtightness'])
    fireEvent.click(lineButton('Airtightness'))
    expect(lineOrder().slice(0, 2)).toEqual(['Airtightness', 'Windows and doors'])
  })
})

